"""Build bilingual DOCX/PDF from Markdown with consistent, plain formatting.

Run: uv run --with python-docx --with weasyprint python docs/project-plan/submission/build_submission.py
Requires pandoc. No content is generated by this script.
"""
from pathlib import Path
import subprocess
import re
from weasyprint import HTML, CSS
from docx import Document
from docx.text.run import Run
from docx.shared import Inches, Pt, RGBColor
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.enum.style import WD_STYLE_TYPE

ROOT = Path(__file__).resolve().parent

def fonts(style, size):
    style.font.name = 'Liberation Serif'
    style.font.size = Pt(size)
    style.font.color.rgb = RGBColor(0, 0, 0)
    style.element.get_or_add_rPr().get_or_add_rFonts().set(qn('w:eastAsia'), 'Droid Sans Fallback')

for language in ['en','zh']:
    source = ROOT / f'project_plan_{language}.md'
    target = ROOT / f'Project_Plan_{language.upper()}.docx'
    subprocess.run(['pandoc',str(source),'-f','markdown','-t','docx','-o',str(target)],check=True)
    doc = Document(target)
    section = doc.sections[0]
    section.page_width, section.page_height = Inches(8.2677), Inches(11.6929)
    section.top_margin = section.bottom_margin = Inches(0.78)
    section.left_margin = section.right_margin = Inches(0.85)
    section.header_distance = section.footer_distance = Inches(0.32)
    for name in ['Normal','Body Text','First Paragraph','Compact']:
        if name in doc.styles:
            style=doc.styles[name];fonts(style,11)
            style.paragraph_format.line_spacing=1.12 if language=='en' else 1.20
            style.paragraph_format.space_after=Pt(6)
    for name,size in [('Heading 1',18),('Heading 2',13),('Heading 3',11)]:
        style=next(s for s in doc.styles if s.style_id == name.replace(' ',''));fonts(style,size);style.font.bold=True
        style.paragraph_format.space_before=Pt(10)
        style.paragraph_format.space_after=Pt(5)
        style.paragraph_format.keep_with_next=True
    # Use a title style, with body sections starting at outline level one.
    heading_styles = {style.style_id: style for style in doc.styles}
    for paragraph in doc.paragraphs[1:]:
        if paragraph.style.style_id == 'Heading2':
            paragraph.style = heading_styles['Heading1']
        elif paragraph.style.style_id == 'Heading3':
            paragraph.style = heading_styles['Heading2']
    fonts(heading_styles['Heading1'],13)
    fonts(heading_styles['Heading2'],11)
    title_style = doc.styles['Title']
    fonts(title_style,18)
    title_style.font.bold = True
    doc.paragraphs[0].style = title_style
    doc.paragraphs[0].paragraph_format.space_before=Pt(0)
    doc.paragraphs[0].paragraph_format.space_after=Pt(8)
    doc.paragraphs[0].paragraph_format.keep_with_next=True
    subtitle = doc.paragraphs[1]
    subtitle.paragraph_format.space_after = Pt(12)
    subtitle.paragraph_format.keep_with_next = True
    for run in subtitle.runs:
        run.font.size = Pt(12)
        run.font.bold = False
        run.font.color.rgb = RGBColor(75, 75, 75)
    hyperlink_style = next(s for s in doc.styles if s.style_id == 'Hyperlink')
    hyperlink_style.font.color.rgb = RGBColor.from_string('245580')
    hyperlink_style.font.underline = False
    in_references=False
    for p in doc.paragraphs:
        if p.text in ['References','参考文献']:
            in_references=True
        elif in_references:
            p.paragraph_format.space_after=Pt(5)
            p.paragraph_format.line_spacing=1.05
            p.paragraph_format.left_indent=Pt(20)
            p.paragraph_format.first_line_indent=Pt(-20)
            p.paragraph_format.keep_together=True
            for element in p._p.iter(qn('w:r')):
                Run(element,p).font.size=Pt(9.5)
        p.paragraph_format.widow_control=True
    grid = doc.styles.add_style('Submission Grid', WD_STYLE_TYPE.TABLE)
    borders = OxmlElement('w:tblBorders')
    for edge in ['top','left','bottom','right','insideH','insideV']:
        border = OxmlElement(f'w:{edge}')
        for key,value in [('val','single'),('sz','4'),('color','BBBBBB')]:
            border.set(qn(f'w:{key}'),value)
        borders.append(border)
    table_properties = OxmlElement('w:tblPr')
    table_properties.append(borders)
    grid.element.append(table_properties)
    member_names = ['Fu Yitong','Li Yitong','Wang Junbo','Xu Ruicong','Zhao Dingcheng']
    for table_index, table in enumerate(doc.tables):
        for row in table.rows:
            for cell in row.cells:
                for paragraph in cell.paragraphs:
                    for run in paragraph.runs:
                        for name in member_names:
                            if name in run.text:
                                run.text = run.text.replace(name,name.replace(' ', '\u00a0'))
        if table_index == 0:
            table.autofit = False
            for column in table.columns:
                column.width = Inches(1.31)
            for row_index, row in enumerate(table.rows):
                for cell in row.cells:
                    cell.width = Inches(1.31)
                    for paragraph in cell.paragraphs:
                        paragraph.paragraph_format.space_before = Pt(0)
                        paragraph.paragraph_format.space_after = Pt(2)
                        paragraph.paragraph_format.keep_with_next = True
                        for run in paragraph.runs:
                            run.font.size = Pt(10)
                            run.bold = row_index == 0
            continue
        table.style=grid
        for i,row in enumerate(table.rows):
            props=row._tr.get_or_add_trPr()
            props.append(OxmlElement('w:cantSplit'))
            if i==0:props.append(OxmlElement('w:tblHeader'))
            for cell in row.cells:
                for p in cell.paragraphs:
                    p.paragraph_format.space_after=Pt(3)
                    p.paragraph_format.space_before=Pt(3)
                    p.paragraph_format.line_spacing=1.08
                    for run in p.runs:
                        run.font.size=Pt(10)
                        if i==0:run.bold=True
        # Keep the date/member column readable; give explanatory text the space.
        widths=[1.20,4.15,1.22] if len(table.columns)==3 else [1.22,5.35]
        table.autofit=False
        for column,width in zip(table.columns,widths):
            column.width=Inches(width)
        for row in table.rows:
            for cell,width in zip(row.cells,widths):cell.width=Inches(width)
    header=section.header.paragraphs[0]
    run=header.add_run('COMP1110 | Project Plan' if language=='en' else 'COMP1110 | 项目计划')
    run.font.size=Pt(9);run.font.color.rgb=RGBColor(95,95,95)
    footer=section.footer.paragraphs[0];footer.alignment=2
    run=footer.add_run();field=OxmlElement('w:fldSimple');field.set(qn('w:instr'),'PAGE');run._r.append(field)
    doc.core_properties.title='Keeping the Topic, Widening the View' if language=='en' else '保留话题，拓宽视角'
    doc.core_properties.author='COMP1110 Project Team'
    doc.save(target)
    html = subprocess.run(['pandoc',str(source),'-f','markdown','-t','html5'],
                          check=True,capture_output=True,text=True).stdout
    html = re.sub(r'<colgroup>.*?</colgroup>', '', html, flags=re.S)
    html = html.replace('<table>', '<table class="team">', 1)
    def keep_names_together(match):
        table_html = match.group(0)
        for name in member_names:
            table_html = table_html.replace(name,name.replace(' ', '&nbsp;'))
        return table_html
    html = re.sub(r'<table\b.*?</table>',keep_names_together,html,flags=re.S)
    css_text = """
        @page { size: A4; margin: 19.8mm 21.6mm;
            @top-left { content: 'COMP1110 | Project Plan'; font: 9pt 'Liberation Serif'; color: #666; }
            @bottom-right { content: counter(page); font: 9pt 'Liberation Serif'; }
        }
        body { font-family: 'Liberation Serif', 'Droid Sans Fallback'; font-size: 11pt; line-height: 1.17; }
        h1 { bookmark-level: none; font-size: 18pt; margin: 0 0 8pt; }
        h1 + p { font-size: 12pt; color: #4b4b4b; margin: 0 0 12pt; break-after: avoid; }
        table.team { margin: 0 0 15pt; break-inside: avoid; break-after: avoid; }
        table.team th, table.team td { width: 20%; border: none; padding: 1pt 0; }
        table.team td { color: #555; }
        h2 { bookmark-level: 1; font-size: 13pt; margin: 12pt 0 6pt; }
        h3 { bookmark-level: 2; font-size: 11pt; margin: 9pt 0 4pt; }
        h1,h2,h3 { break-after: avoid; }
        p { margin: 0 0 7pt; orphans: 2; widows: 2; }
        a { color: #245580; text-decoration: none; }
        a[href^="https://doi.org"]:not(:has(em)) { white-space: nowrap; }
        table { border-collapse: collapse; width: 100%; font-size: 10pt; margin: 8pt 0; }
        th,td { border: 0.5pt solid #bbb; padding: 4pt; text-align: left; vertical-align: top; }
        tr { break-inside: avoid; }
        table { table-layout: fixed; }
        th:first-child,td:first-child { width: 19%; }
        th:nth-child(3),td:nth-child(3) { width: 19%; }

        h2#references ~ p, h2#参考文献 ~ p { font-size: 9.5pt; line-height: 1.1; margin-bottom: 6pt; padding-left: 20pt; text-indent: -20pt; break-inside: avoid; }
    """
    if language == 'zh':
        css_text = css_text.replace("content: 'COMP1110 | Project Plan'; font: 9pt 'Liberation Serif';", "content: 'COMP1110 | 项目计划'; font: 9pt 'Droid Sans Fallback';")
    css = CSS(string=css_text)
    HTML(string='<html lang="'+language+'"><meta charset="utf-8"><title>'+doc.core_properties.title+'</title><body>'+html+'</body></html>').write_pdf(
        target.with_suffix('.pdf'), stylesheets=[css])
    print(target.name, 'and PDF generated')
